#!/usr/bin/env bash
set -euo pipefail
if [[ $# != 1 ]]; then
    echo "Usage: $0 <project-directory>" >&2
    exit 1
fi
project=$(cd "$1" && pwd)
verify="$project/anodized-verify-aeneas"
[[ -f "$project/Cargo.toml" && -f "$verify/lakefile.toml" ]] || {
    echo "Project must contain Cargo.toml and anodized-verify-aeneas/lakefile.toml: $project" >&2
    exit 1
}
cd "$(dirname "$0")/.."
root=$PWD
# Cargo builds proc macros for the host; pass the cfg to both host and target.
if [[ ${CARGO_ENCODED_RUSTFLAGS+x} ]]; then
    export CARGO_ENCODED_RUSTFLAGS="${CARGO_ENCODED_RUSTFLAGS:+$CARGO_ENCODED_RUSTFLAGS$'\x1f'}--cfg"$'\x1f'"anodized_charon"$'\x1f'"--check-cfg=cfg(anodized_charon)"
else
    export RUSTFLAGS="${RUSTFLAGS:+$RUSTFLAGS }--cfg anodized_charon --check-cfg=cfg(anodized_charon)"
fi
tag=$(awk -F'"' '/^\[/{name=""} /^name = /{name=$2} /^rev = / && name=="aeneas"{print $2}' "$verify/lakefile.toml")
: "${tag:?no Aeneas revision in $verify/lakefile.toml}"
bundle="$verify/.aeneas"
[[ "$("$bundle/aeneas" -version 2>/dev/null || true)" == "aeneas $tag" && -x "$bundle/charon" ]] || {
    echo "Run ./scripts/install-aeneas.sh '$project' first." >&2
    exit 1
}

# Stage output before touching committed translations; protect handwritten models.
tmp=$(mktemp -d "${TMPDIR:-/tmp}/anodized-translation.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
llbc="$tmp/translation.llbc"
subdir=translation
echo "Translating $project"
# Extract Anodized's specification helpers so Lean can reduce their bodies.
(cd "$project" && "$bundle/charon" cargo --preset=aeneas --duplicate-defaulted-methods --include 'anodized::__' --dest-file "$llbc" -- -Zhost-config -Ztarget-applies-to-host --config 'host.rustflags=["--cfg", "anodized_charon"]' --locked)
[[ -f "$llbc" ]] || { echo "Charon did not produce $llbc" >&2; exit 1; }
"$bundle/aeneas" "$llbc" -backend lean -dest "$tmp" -subdir "$subdir" -split-files -emit-json
generated="$tmp/$subdir"
for template in "$generated"/*_Template.lean; do
    [[ -f "$template" ]] || continue
    mv "$template" "${template%_Template.lean}.lean"
done
[[ -f "$tmp/translation.json" ]] || { echo 'Aeneas did not produce translation.json' >&2; exit 1; }
sed 's/_Template\.lean/.lean/g' "$tmp/translation.json" > "$generated/translation.json"
for external in "$verify"/translation/*External.lean; do
    [[ -f "$external" ]] || continue
    if [[ "$(head -n 1 "$external")" != '-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS' ]]; then
        echo "Refusing to overwrite handwritten external model: $external" >&2
        exit 1
    fi
done
rm -rf "$verify/translation"
mv "$generated" "$verify/translation"
