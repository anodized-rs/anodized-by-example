#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
root=$PWD
tag=$(awk -F'"' '/^\[/{name=""} /^name = /{name=$2} /^rev = / && name=="aeneas"{print $2}' lakefile.toml)
: "${tag:?no Aeneas revision in lakefile.toml}"
[[ "$(.aeneas/aeneas -version 2>/dev/null || true)" == "aeneas $tag" && -x .aeneas/charon ]] || {
    echo 'Run ./scripts/aeneas-install.sh first.' >&2
    exit 1
}

# Stage output before touching committed translations; protect handwritten models.
tmp=$(mktemp -d "${TMPDIR:-/tmp}/anodized-translation.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
found=0
for manifest in examples/*/Cargo.toml; do
    [[ -f "$manifest" ]] || continue
    found=1
    crate_dir=${manifest%/Cargo.toml}
    crate=${crate_dir##*/}
    llbc="$tmp/${crate//-/_}.llbc"
    subdir="$crate_dir/translation"
    echo "Translating $crate_dir"
    (cd "$crate_dir" && "$root/.aeneas/charon" cargo --preset=aeneas --dest-file "$llbc" -- --locked)
    [[ -f "$llbc" ]] || { echo "Charon did not produce $llbc" >&2; exit 1; }
    "$root/.aeneas/aeneas" "$llbc" -backend lean -dest "$tmp" -subdir "$subdir" -split-files -emit-json
    generated="$tmp/$subdir"
    for template in "$generated"/*_Template.lean; do
        [[ -f "$template" ]] || continue
        mv "$template" "${template%_Template.lean}.lean"
    done
    [[ -f "$tmp/translation.json" ]] || { echo 'Aeneas did not produce translation.json' >&2; exit 1; }
    sed 's/_Template\.lean/.lean/g' "$tmp/translation.json" > "$generated/translation.json"
    rm "$tmp/translation.json"
    for external in "$crate_dir"/translation/*External.lean; do
        [[ -f "$external" ]] || continue
        if [[ "$(head -n 1 "$external")" != '-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS' ]]; then
            echo "Refusing to overwrite handwritten external model: $external" >&2
            exit 1
        fi
    done
    rm -rf "$crate_dir/translation"
    mv "$generated" "$crate_dir/translation"
done
[[ $found == 1 ]] || { echo 'No example crates found.' >&2; exit 1; }
